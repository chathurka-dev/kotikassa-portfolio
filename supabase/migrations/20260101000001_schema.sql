-- Enable UUID generation
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ── families ─────────────────────────────────────────────────
-- The tenant root. Every other table references this.
CREATE TABLE families (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name       TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ── profiles ─────────────────────────────────────────────────
-- One profile per Supabase auth user.
-- Created automatically on signup via trigger (see below).
CREATE TABLE profiles (
  id           UUID PRIMARY KEY REFERENCES auth.users ON DELETE CASCADE,
  family_id    UUID REFERENCES families ON DELETE SET NULL,
  display_name TEXT NOT NULL DEFAULT '',
  role         TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('admin', 'member')),
  avatar_url   TEXT,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ── family_invites ───────────────────────────────────────────
-- One-time invite tokens generated by family admins.
CREATE TABLE family_invites (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  family_id  UUID NOT NULL REFERENCES families ON DELETE CASCADE,
  created_by UUID NOT NULL REFERENCES profiles ON DELETE CASCADE,
  token      TEXT NOT NULL UNIQUE DEFAULT encode(gen_random_bytes(32), 'hex'),
  expires_at TIMESTAMPTZ NOT NULL DEFAULT (now() + INTERVAL '48 hours'),
  used_at    TIMESTAMPTZ,
  used_by    UUID REFERENCES profiles ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ── categories ───────────────────────────────────────────────
-- Expense categories, customizable per family.
CREATE TABLE categories (
  id         UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  family_id  UUID NOT NULL REFERENCES families ON DELETE CASCADE,
  name       TEXT NOT NULL,
  icon       TEXT NOT NULL DEFAULT '📦',
  color      TEXT NOT NULL DEFAULT '#6b7280',
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- Unique name per family
  UNIQUE (family_id, name)
);

-- ── receipts ─────────────────────────────────────────────────
-- One record per scanned photo. Multiple expense_items point to one receipt.
CREATE TABLE receipts (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  family_id      UUID NOT NULL REFERENCES families ON DELETE CASCADE,
  uploaded_by    UUID REFERENCES profiles ON DELETE SET NULL,
  image_url      TEXT,
  store_name     TEXT,
  receipt_date   DATE,
  total_amount   NUMERIC(10, 2),
  ocr_raw_text   TEXT,
  ocr_confidence NUMERIC(5, 2), -- 0.00 to 100.00
  -- 'pending_review' = OCR done, waiting for user confirmation
  -- 'confirmed'      = user has reviewed and saved items
  -- 'manual'         = entered manually without a photo
  status         TEXT NOT NULL DEFAULT 'pending_review'
                 CHECK (status IN ('pending_review', 'confirmed', 'manual')),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ── expense_items ────────────────────────────────────────────
-- Individual line items — the core financial record.
-- Can come from a receipt scan or be entered manually (receipt_id IS NULL).
CREATE TABLE expense_items (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  family_id    UUID NOT NULL REFERENCES families ON DELETE CASCADE,
  receipt_id   UUID REFERENCES receipts ON DELETE SET NULL,
  added_by     UUID REFERENCES profiles ON DELETE SET NULL,
  -- NULL category = uncategorized (shown in review)
  category_id  UUID REFERENCES categories ON DELETE SET NULL,
  name         TEXT NOT NULL,
  amount       NUMERIC(10, 2) NOT NULL CHECK (amount >= 0),
  quantity     NUMERIC(10, 3) NOT NULL DEFAULT 1,
  unit         TEXT,             -- 'kg', 'kpl', 'g', 'l', etc.
  expense_date DATE NOT NULL,
  is_manual    BOOLEAN NOT NULL DEFAULT false,
  notes        TEXT,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ── income_entries ───────────────────────────────────────────
CREATE TABLE income_entries (
  id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  family_id           UUID NOT NULL REFERENCES families ON DELETE CASCADE,
  added_by            UUID REFERENCES profiles ON DELETE SET NULL,
  source              TEXT NOT NULL DEFAULT 'other'
                      CHECK (source IN ('salary', 'freelance', 'benefit', 'rental', 'other')),
  description         TEXT NOT NULL,
  amount              NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
  income_date         DATE NOT NULL,
  is_recurring        BOOLEAN NOT NULL DEFAULT false,
  recurrence_interval TEXT CHECK (recurrence_interval IN ('weekly', 'monthly', 'yearly')),
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ── savings_goals ────────────────────────────────────────────
CREATE TABLE savings_goals (
  id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  family_id      UUID NOT NULL REFERENCES families ON DELETE CASCADE,
  created_by     UUID REFERENCES profiles ON DELETE SET NULL,
  name           TEXT NOT NULL,
  target_amount  NUMERIC(10, 2) NOT NULL CHECK (target_amount > 0),
  current_amount NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (current_amount >= 0),
  deadline       DATE,
  -- When true, only the creator can see this goal
  is_private     BOOLEAN NOT NULL DEFAULT false,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ── budgets ──────────────────────────────────────────────────
-- Monthly budget per category per family.
CREATE TABLE budgets (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  family_id   UUID NOT NULL REFERENCES families ON DELETE CASCADE,
  category_id UUID NOT NULL REFERENCES categories ON DELETE CASCADE,
  -- Always the 1st day of the month: '2026-06-01', '2026-07-01', etc.
  month       DATE NOT NULL,
  amount      NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- One budget per category per month per family
  UNIQUE (family_id, category_id, month)
);

-- ── item_category_memory ─────────────────────────────────────
-- Remembers what category a user assigned to a product name.
-- Used by the smart suggestion system in manual entry and OCR review.
CREATE TABLE item_category_memory (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  family_id   UUID NOT NULL REFERENCES families ON DELETE CASCADE,
  -- Normalized product name (lowercase, trimmed)
  item_name   TEXT NOT NULL,
  category_id UUID NOT NULL REFERENCES categories ON DELETE CASCADE,
  -- How many times this mapping has been confirmed
  confidence  INTEGER NOT NULL DEFAULT 1,
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (family_id, item_name)
);

-- ── Indexes ───────────────────────────────────────────────────
-- All queries filter by family_id first — index every FK to families
CREATE INDEX idx_profiles_family_id          ON profiles (family_id);
CREATE INDEX idx_categories_family_id        ON categories (family_id, sort_order);
CREATE INDEX idx_receipts_family_id          ON receipts (family_id, receipt_date DESC);
CREATE INDEX idx_expense_items_family_id     ON expense_items (family_id, expense_date DESC);
CREATE INDEX idx_expense_items_category_id   ON expense_items (category_id);
CREATE INDEX idx_expense_items_receipt_id    ON expense_items (receipt_id);
CREATE INDEX idx_income_entries_family_id    ON income_entries (family_id, income_date DESC);
CREATE INDEX idx_savings_goals_family_id     ON savings_goals (family_id);
CREATE INDEX idx_budgets_family_month        ON budgets (family_id, month DESC);
CREATE INDEX idx_item_memory_family_name     ON item_category_memory (family_id, item_name);

-- ── Trigger: auto-create profile on signup ───────────────────
-- When a user signs up via Supabase Auth, create an empty profile row.
CREATE OR REPLACE FUNCTION handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  INSERT INTO profiles (id, display_name)
  VALUES (NEW.id, COALESCE(NEW.raw_user_meta_data->>'display_name', ''));
  RETURN NEW;
END;
$$;

CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION handle_new_user();
